// Systems lists every system category.
func Systems() []System {
	return []System{
		SystemCardPayment, SystemLoansGranted, SystemLoanCollections, SystemLoanInterest,
		SystemLoanCancellation, SystemBrokerFunding, SystemInvestmentFees,
	}
}
