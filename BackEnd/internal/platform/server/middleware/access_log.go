// RequestIDHeader carries the request id in both directions.
const RequestIDHeader = "X-Request-ID"

// requestIDContextKey is the gin context key holding the request id.
const requestIDContextKey = "request_id"

// validRequestID accepts the ids generated by us, the Next.js proxy and
// common edge proxies; anything else (too long, odd characters that could
// forge log lines) is replaced.
var validRequestID = regexp.MustCompile(`^[A-Za-z0-9._:-]{8,64}$`)

// RequestID propagates the caller's X-Request-ID (when well formed) or mints
// a new one; it is echoed in the response, stored in the gin context and the
// request context (observability.RequestIDFromContext) for logs and spans.
func RequestID() gin.HandlerFunc {
	return func(c *gin.Context) {
		id := strings.TrimSpace(c.GetHeader(RequestIDHeader))
		if !validRequestID.MatchString(id) {
			id = uuid.NewString()
		}
		c.Set(requestIDContextKey, id)
		c.Header(RequestIDHeader, id)
		ctx := observability.ContextWithRequestID(c.Request.Context(), id)
		ctx = context.WithValue(ctx, apperrors.ContextKeyRequestID, id) // AppError.RequestID
		c.Request = c.Request.WithContext(ctx)
		c.Next()
	}
}

// GetRequestID returns the request id set by RequestID.
func GetRequestID(c *gin.Context) string {
	return c.GetString(requestIDContextKey)
}

// AccessLog writes one concise structured line per request:
//
//	{"level":"info","method":"GET","route":"/account","status":200,
//	 "duration_ms":4.2,"bytes":512,"request_id":"…","trace_id":"…","msg":"request"}
//
// The route template is logged instead of the raw path (no ids, no query
// strings) and no client IP / user agent / user id is recorded.
//
// Mode (ACCESS_LOG): "all" logs everything (fast 2xx/3xx/4xx sampled by
// AccessLogSampleRate), "errors" only 5xx and requests slower than
// SlowRequestThreshold, "off" nothing. Health checks and /metrics are only
// logged when they fail.
func AccessLog(cfg config.LoggingConfig, logger zerolog.Logger) gin.HandlerFunc {
	mode := cfg.AccessLog
	if mode == "" {
		mode = "errors"
	}
	if mode == "off" {
		return func(c *gin.Context) { c.Next() }
	}
	slow := cfg.SlowRequestThreshold
	if slow <= 0 {
		slow = time.Second
	}
	sample := cfg.AccessLogSampleRate
	quiet := DefaultSkipTracing()

	return func(c *gin.Context) {
		start := time.Now()
		c.Next()
		elapsed := time.Since(start)

		route := c.FullPath()
		if route == "" {
			route = UnmatchedRoute
		}
		status := c.Writer.Status()
		isErr := status >= http.StatusInternalServerError
		isSlow := elapsed >= slow && !DefaultStreamingRoutes()[route]

		if !shouldLog(mode, sample, isErr, isSlow, quiet[route]) {
			return
		}

		var ev *zerolog.Event
		switch {
		case isErr:
			ev = logger.Error()
		case isSlow:
			ev = logger.Warn()
		default:
			ev = logger.Info()
		}
		ev = ev.
			Str("method", c.Request.Method).
			Str("route", route).
			Int("status", status).
			Float64("duration_ms", float64(elapsed.Microseconds())/1000).
			Int("bytes", max(c.Writer.Size(), 0))
		if id := GetRequestID(c); id != "" {
			ev = ev.Str(observability.RequestIDField, id)
		}
		if sc := trace.SpanContextFromContext(c.Request.Context()); sc.IsValid() {
			ev = ev.Str(observability.TraceIDField, sc.TraceID().String())
		}
		if isSlow {
			ev = ev.Bool("slow", true)
		}
		if n := len(c.Errors); n > 0 {
			ev = ev.Int("errors", n)
		}
		ev.Msg("request")
	}
}

func shouldLog(mode string, sample float64, isErr, isSlow, quietRoute bool) bool {
	if isErr || isSlow {
		return true
	}
	if mode != "all" || quietRoute {
		return false
	}
	if sample >= 1 {
		return true
	}
	return sample > 0 && rand.Float64() < sample //nolint:gosec // log sampling, not security
}
